"""One command regenerates every figure, table and number of the paper.

    python make_all.py            # run all factory scripts, write numbers.tex and _build/pending.md
    python make_all.py --pdf      # also compile main.pdf with latexmk

Each figures/make_*.py and tables/make_*.py is independent; a script whose inputs are missing reports
[pending] and its outputs render as \\pending boxes in the PDF until the data land.
"""
import json
import subprocess
import sys
from pathlib import Path

PAPER = Path(__file__).resolve().parent
NUM_DIR = PAPER / "_build" / "numbers"


def run_scripts():
    status = {}
    scripts = sorted((PAPER / "figures").glob("make_*.py")) + sorted((PAPER / "tables").glob("make_*.py"))
    for s in scripts:
        r = subprocess.run([sys.executable, "-X", "utf8", str(s)], cwd=PAPER, capture_output=True, text=True,
                           encoding="utf-8", errors="replace")
        line = (r.stdout.strip().splitlines() or [""])[-1]
        if r.returncode != 0:
            line = f"[error] {s.stem}: " + (r.stderr.strip().splitlines() or ["?"])[-1]
        status[s.stem] = line
        print(line)
    return status


def write_numbers():
    vals = {}
    for j in sorted(NUM_DIR.glob("*.json")):
        for k, v in json.loads(j.read_text(encoding="utf-8")).items():
            vals[k] = (v, j.stem)
    old = PAPER / "numbers.tex"  # keep shipped values whose inputs are not in the public release
    if old.exists():
        import re
        for m in re.finditer(r"^\\defV\{([^}]+)\}\{(.*)\}% (.*)$", old.read_text(encoding="utf-8"), re.M):
            vals.setdefault(m.group(1), (m.group(2), m.group(3)))
    lines = ["% numbers.tex -- generated by make_all.py from result files; do not edit",
             "% \\V{key} prints the value; keys that are not defined here print a \\pending box."]
    for k in sorted(vals):
        v, who = vals[k]
        lines.append(f"\\defV{{{k}}}{{{v}}}% {who}")
    (PAPER / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return set(vals)


def used_keys():
    import re
    keys = set()
    for t in [PAPER / "main.tex", *sorted((PAPER / "sections").glob("*.tex"))]:
        keys |= set(re.findall(r"\\V\{([^}]+)\}", t.read_text(encoding="utf-8")))
    return keys


def missing_figures():
    import re
    out = []
    for t in sorted((PAPER / "sections").glob("*.tex")):
        for name in re.findall(r"\\fig(?:col|wide)\{([^}]+)\}", t.read_text(encoding="utf-8")):
            if not (PAPER / "figures" / f"{name}.pdf").exists():
                out.append(name)
        for name in re.findall(r"\\tab\{([^}]+)\}", t.read_text(encoding="utf-8")):
            if not (PAPER / "tables" / f"{name}.tex").exists():
                out.append(name)
    return out


def main():
    NUM_DIR.mkdir(parents=True, exist_ok=True)
    status = run_scripts()
    have = write_numbers()
    pend_keys = sorted(used_keys() - have)
    pend_figs = missing_figures()
    lines = ["# Pending items (generated by make_all.py)", "",
             "## Scripts", ""] + [f"- {v}" for v in status.values() if not v.startswith("[ok]")] + \
            ["", "## Numbers used in the text without a value", ""] + [f"- `{k}`" for k in pend_keys] + \
            ["", "## Figures/tables referenced but not generated", ""] + [f"- `{k}`" for k in pend_figs]
    (PAPER / "_build" / "pending.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"numbers: {len(have)} defined, {len(pend_keys)} pending; missing floats: {len(pend_figs)}")
    if "--pdf" in sys.argv:
        subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "main.tex"], cwd=PAPER)


if __name__ == "__main__":
    main()
